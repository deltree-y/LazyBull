"""P5b T5 回撤裁判（校准器库层）：MDD/D_k 读数、崩盘窗、λ/ζ 注入求解、两个方向阈值、
holdout 逐单元验收、功效/MDE、回撤仪器 manifest 与报告。

边界（设计 v4 §5.4 + 架构 F22）
==============================
- 只做**历史**校准：不运行真实前向影子、不等待真实日历、不注册真实候选；
- 产物只落**新** campaign 的 ``reports/``（``data/paper_shadow/p5b_testbed/<id>/reports/``），
  不写 ``data/paper`` / ``data/runs`` / ``data/models``，不写 ``LedgerEntry``；
- 证据一律 ``evidence_class=calibration_only``；H5 闸门由用户在合并验收时确认；
- **不改写收益仪器**：``referee/`` 根下 11 个模块与其冻结 manifest 均只读引用，本子包只以
  上游哈希（``545d2be4…`` / ``af37b217…``）链接父证据。

模块划分
========
- ``mdd``：MDD 与 ``D_k`` 的唯一实现（log 尺度、首点计入、pp 换算、逐 look horizon）；
- ``crash_window``：B0 最后 500 收益样本上的 episode 识别与冻结选窗；
- ``injection``：DD-I/DD-W 注入公式与 101 点扫描 + ≤80 次细分的向量化求解器；
- ``sampling``：回撤裁判独立命名空间的 seed 子流；
- ``realizations``：B0 冻结窗口与 ``x = B0 + n`` 配对噪声实现；
- ``thresholds``：``c^W_k``（min over scene）与 ``c^I_k``（max over scene）+ 方向自检；
- ``holdout``：逐单元 Wilson 上界门（两个方向分别判定）；
- ``power``：纯注入档网格、检出率、可构造率与两个 MDE；
- ``artifacts``：确定性独占落盘；
- ``manifest``／``sections``：§5.5 回撤清单冻结、三环互链与上游链接；
- ``report``：判定表与 §7.2 回撤部分报告；
- ``calibration``：编排（冻结 → 训练 → holdout → 功效 → 报告）。
"""

